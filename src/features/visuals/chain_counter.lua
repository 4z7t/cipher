local feature = Feature:new("chain_counter");
feature.current = Converted["_Frame"];

local sg = Instance.new("ScreenGui", game:GetService("CoreGui"));
sg.IgnoreGuiInset = true;
sg.Enabled = false;
feature.current.Parent = sg;
aztup.maid:give_task(sg);

function feature:enable()
    sg.Enabled = true;
	feature.stacks = 0;

	self.added_hook = EffectReplicatorHandler:hook("added", function(effect)
		setthreadidentity(8)
		if effect.Class == "PerfectStack" then
			for _, frame in pairs(feature.current:GetChildren()) do
				services.TweenService:Create(frame, TweenInfo.new(1), {
					BackgroundTransparency = 1
				}):Play();
			end;
			feature.stacks = 0;
		elseif effect.Class == "PerfectionCool" then
			feature.stacks = math.min(feature.stacks + 1, 20);

			for _, frame in pairs(feature.current:GetChildren()) do
				if tonumber(frame.Name) > feature.stacks then
					services.TweenService:Create(frame, TweenInfo.new(1), {
						BackgroundTransparency = 1
					}):Play();
					continue				
end;

				services.TweenService:Create(frame, TweenInfo.new(0.25), {
					BackgroundTransparency = 0.65
				}):Play();
			end;
		end
	end);
	
	self.removing_hook = EffectReplicatorHandler:hook("removed", function(effect)
		if effect.Class == "PerfectStack" then
			for _, frame in pairs(feature.current:GetChildren()) do
				services.TweenService:Create(frame, TweenInfo.new(1), {
					BackgroundTransparency = 1
				}):Play();
			end;
			feature.stacks = 0;
			
		end;
	end);

	
    for _, frame in pairs(feature.current:GetChildren()) do
        frame.BackgroundTransparency = 1;
    end;
end;

function feature:disable()
	if self.removing_hook then
		self.added_hook:remove();
		self.removing_hook:remove();
	end;

    sg.Enabled = false;

    for _, frame in pairs(feature.current:GetChildren()) do
        frame.BackgroundTransparency = 1;
    end;
end;

return feature